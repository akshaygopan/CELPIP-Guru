#!/usr/bin/env node
// Compiles data/tests/*.json into src/generated/: one lazily-loaded module per test
// (content without answers + an encoded answer key) and an index for the library.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { shuffleOptions, splitTest, encodeKey, summarize } from '../src/lib/bankShape.js';
import { validateTest } from './validate-bank.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'data', 'tests');
const out = path.join(root, 'src', 'generated');
fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(path.join(out, 'tests'), { recursive: true });

const files = fs.readdirSync(src).filter(f => /^t\d+\.json$/.test(f)).sort((a, b) => parseInt(a.slice(1)) - parseInt(b.slice(1)));
const index = [];
const skipped = [];
for (const f of files) {
  let raw;
  try { raw = JSON.parse(fs.readFileSync(path.join(src, f), 'utf8')); } catch (e) { skipped.push(`${f} (invalid JSON)`); continue; }
  // Only tests that pass the bank rules are published; anything else is left out with a warning.
  const { errors } = validateTest(raw, { strict: !/^t(0\d|10)$/.test(raw.id) });
  if (errors.length) { skipped.push(`${f} (${errors.length} problem${errors.length > 1 ? 's' : ''})`); continue; }
  const full = shuffleOptions(raw);
  const { content, key } = splitTest(full);
  fs.writeFileSync(path.join(out, 'tests', full.id + '.js'), `export default ${JSON.stringify({ content, key: encodeKey(key, full.id) })};\n`);
  index.push(summarize(full));
}
const practice = JSON.parse(fs.readFileSync(path.join(root, 'data', 'practice.json'), 'utf8'));
const loaders = index.map(t => `  ${JSON.stringify(t.id)}: () => import('./tests/${t.id}.js')`).join(',\n');
fs.writeFileSync(path.join(out, 'bank-index.js'),
  `// Generated by scripts/build-bank.mjs – do not edit.\nexport const TESTS = ${JSON.stringify(index)};\nexport const PRACTICE = ${JSON.stringify(practice)};\nexport const loaders = {\n${loaders}\n};\n`);
console.log(`Built ${index.length} tests into src/generated/`);
if (skipped.length) console.warn(`Skipped ${skipped.length} test(s) that fail validation – run npm run validate:\n  ` + skipped.join('\n  '));
